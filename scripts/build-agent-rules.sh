#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"

# Make glob ordering consistent regardless of the caller's locale.
export LC_ALL=C
shopt -s nullglob
rule_files=("$repo_root"/rules/*.md)

if (( ${#rule_files[@]} == 0 )); then
  printf 'No rule files found in %s/rules/*.md\n' "$repo_root" >&2
  exit 1
fi

# Replace the output only after every rule file has been read successfully.
output="$(mktemp "$repo_root/.AGENTS.md.XXXXXX")"
trap 'rm -f -- "$output"' EXIT

{
  printf '# Project agent instructions\n\n'
  printf '<!-- Generated by scripts/build-agent-rules.sh from rules/*.md. Do not edit directly. -->\n'
  for rule_file in "${rule_files[@]}"; do
    printf '\n<!-- Source: rules/%s -->\n\n' "${rule_file##*/}"
    cat -- "$rule_file"
  done
} > "$output"

chmod 644 "$output"
mv -- "$output" "$repo_root/AGENTS.md"

defmodule ElixirMixir do
  @moduledoc """
  Entry point for the elixir-mixir experimental Elixir/OTP runtime.
  """

  @doc """
  Returns the bootstrap hello-world greeting.

  ## Examples

      iex> ElixirMixir.hello()
      :world

  """
  @spec hello() :: :world
  def hello do
    :world
  end
end
